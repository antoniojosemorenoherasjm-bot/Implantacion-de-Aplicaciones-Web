num1 = float(input("Introduce el primer número: "))
num2 = float(input("Introduce el segundo número: "))

suma = num1 + num2
resta = num1 - num2
division = num1 / num2
multiplicacion = num1 * num2

print(f'La suma de los dos números es {suma}')
print(f'La resta del primer número menos el segundo es {resta}')
print(f'El primer número dividido entre el segundo es {division:.2f}')
print(f'La multiplicación de los dos números es {multiplicacion}')
